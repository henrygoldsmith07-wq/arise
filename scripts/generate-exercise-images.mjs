// scripts/generate-exercise-images.mjs
// Generates src/lib/exerciseImages.js from @bryllim/workout-guide manifest.
// MIT code / CC BY-SA 4.0 assets — attribution preserved in the output file.
//
// Copies EVERYTHING the package knows about each matched exercise: all
// animation frames, name, exercise type, equipment, primary/secondary
// muscles and stretch flag.

import fs from 'node:fs';
import path from 'node:path';

const manifest = JSON.parse(fs.readFileSync(path.resolve('node_modules/@bryllim/workout-guide/manifest.json'), 'utf8'));
const exercises = manifest;

const ariseSrc = fs.readFileSync('src/lib/data.js', 'utf8');
const idRe = /id:\s*'([^']+)'/g;
const ariseIds = new Set();
let m;
while((m = idRe.exec(ariseSrc))) ariseIds.add(m[1]);

const toEntry = ex => ({
  slug: ex.slug,
  name: ex.name,
  exerciseType: ex.exerciseType,
  equipment: ex.equipment,
  frames: ex.frames.map(f => f.index), // every frame the package ships
  primaryMuscle: ex.primaryMuscle,
  secondaryMuscles: ex.secondaryMuscles || [],
  isStretch: !!ex.isStretch,
  license: 'CC BY-SA 4.0',
  creator: 'Bryl Lim',
});

const imageMap = {};
const usedSlugs = new Set();

// Pass 1: direct slug match.
for(const aid of ariseIds){
  const ex = exercises.find(e => e.slug === aid);
  if(ex){
    imageMap[aid] = toEntry(ex);
    usedSlugs.add(ex.slug);
  }
}

// Pass 2: curated aliases for known name differences.
const ALIASES = {
  'bench-press-barbell': 'bench-press',
  'overhead-press-barbell': 'overhead-press',
  'dumbbell-row': 'one-arm-dumbbell-row',
  'cable-row': 'seated-row',
  'tricep-dip-bench': 'dip',
};
for(const [ariseId, slug] of Object.entries(ALIASES)){
  if(!slug || !ariseIds.has(ariseId) || imageMap[ariseId]) continue;
  const ex = exercises.find(e => e.slug === slug);
  if(ex && !usedSlugs.has(ex.slug)){
    imageMap[ariseId] = toEntry(ex);
    usedSlugs.add(ex.slug);
  }
}

// Pass 3: conservative auto-aliases. Strip kit words from BOTH sides and
// accept only when the remaining movement words are UNIQUE in the package and
// unclaimed. Ambiguous cores (bench-press vs dumbbell-bench-press) stay
// unmapped rather than risk showing the wrong illustration.
const KIT_WORDS = new Set(['barbell','dumbbell','dumbbells','machine','cable','cables','kettlebell','band','bands','plate','plates','bodyweight']);
const coreKey = slug => slug.split('-').filter(w => !KIT_WORDS.has(w)).join('|');
const pkgByCore = new Map();
for(const e of exercises){
  const k = coreKey(e.slug);
  if(!pkgByCore.has(k)) pkgByCore.set(k, []);
  pkgByCore.get(k).push(e);
}
const claimedCores = new Set([...usedSlugs].map(s => coreKey(s)));
const autoAliases = [];
for(const aid of [...ariseIds].sort()){
  if(imageMap[aid]) continue;
  const k = coreKey(aid);
  const candidates = pkgByCore.get(k) || [];
  const unclaimed = candidates.filter(e => !usedSlugs.has(e.slug));
  if(candidates.length !== 1 || unclaimed.length !== 1 || claimedCores.has(k)) continue;
  const ex = unclaimed[0];
  imageMap[aid] = toEntry(ex);
  usedSlugs.add(ex.slug);
  claimedCores.add(k);
  autoAliases.push(`${aid} -> ${ex.slug}`);
}

// Output module
const out = `// exerciseImages.js — auto-generated by scripts/generate-exercise-images.mjs
// Illustration source: @bryllim/workout-guide v1.0.0 (302 exercises, 906 SVG frames)
// Assets: CC BY-SA 4.0 © Bryl Lim (https://bryllim.com) — derived from Everkinetic.
// Code: MIT. Attribution must be preserved when shipping these images.
//
// Each entry copies the package's full record for that lift: every animation
// frame, name, exercise type (weight_reps / timed), equipment and muscle data.

export const IMAGE_BASE = 'https://bryllim.github.io/workout-guide/frames';

/**
 * Returns { url, alt, name, exerciseType, equipment, primaryMuscle,
 * secondaryMuscles, isStretch, license, creator } or null.
 * frame is 1-based and clamped to the available frames; defaults to 1 (start).
 */
export function getExerciseImage(exerciseId, frame = 1){
  const entry = EXERCISE_IMAGES[exerciseId];
  if(!entry) return null;
  const n = Math.max(1, Math.min(entry.frames.length, Math.round(frame)));
  return {
    url: \`\${IMAGE_BASE}/\${entry.slug}/frame-\${n}.svg\`,
    alt: entry.name ? \`\${entry.name} — \${entry.primaryMuscle}\` : \`\${entry.primaryMuscle} exercise\`,
    name: entry.name,
    exerciseType: entry.exerciseType,
    equipment: entry.equipment,
    primaryMuscle: entry.primaryMuscle,
    secondaryMuscles: entry.secondaryMuscles,
    isStretch: entry.isStretch,
    license: entry.license,
    creator: entry.creator,
  };
}

/** True if this exercise has illustration frames available. */
export function hasExerciseImage(exerciseId){
  return !!EXERCISE_IMAGES[exerciseId];
}

/** All frame indices for an exercise (the full animation sequence). */
export function getImageFrames(exerciseId){
  const entry = EXERCISE_IMAGES[exerciseId];
  return entry ? entry.frames : [];
}

/**
 * Full package metadata for an exercise: name, exerciseType, equipment,
 * primary/secondary muscles, stretch flag and frame count. Null when unknown.
 */
export function getExerciseMeta(exerciseId){
  const entry = EXERCISE_IMAGES[exerciseId];
  if(!entry) return null;
  return {
    name: entry.name,
    exerciseType: entry.exerciseType,
    equipment: entry.equipment,
    primaryMuscle: entry.primaryMuscle,
    secondaryMuscles: entry.secondaryMuscles,
    isStretch: entry.isStretch,
    frames: entry.frames.length,
    license: entry.license,
    creator: entry.creator,
  };
}

/** All package slugs not yet mapped to an Arise exercise (for library expansion). */
export function getUnmatchedSlugs(){
  return ${JSON.stringify(exercises.filter(e => !usedSlugs.has(e.slug)).map(e => ({ slug: e.slug, name: e.name, muscle: e.primaryMuscle, equipment: e.equipment })), null, 2)};
}

const EXERCISE_IMAGES = ${JSON.stringify(imageMap, null, 2)};
`;
fs.writeFileSync('src/lib/exerciseImages.js', out);

const unmatchedCount = exercises.length - usedSlugs.size;
console.log(`Mapped: ${Object.keys(imageMap).length} / ${ariseIds.size} Arise exercises have images`);
console.log(`Auto-aliases added: ${autoAliases.length}`);
for(const a of autoAliases) console.log(`  ${a}`);
console.log(`Package total: ${exercises.length} · still unmatched: ${unmatchedCount}`);
