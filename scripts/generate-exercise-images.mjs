// scripts/generate-exercise-images.mjs
// Generates the compact runtime registry in src/lib/exerciseImages.js from
// @bryllim/workout-guide's manifest.
// MIT code / CC BY-SA 4.0 assets — attribution preserved in the output file.
//
// The production module deliberately does NOT copy the full upstream manifest.
// Arise already owns canonical exercise name/equipment/primary-muscle data in
// src/lib/data.js, every mapped workout-guide record currently has exactly
// three frames, and licensing/creator values are global constants. Shipping
// those values 295 times used to cost ~7.3 kB gzip in a lazy JS chunk.
//
// Runtime tuples therefore retain only data that cannot be derived from Arise:
// [upstream slug, compact exercise-type code, secondary-muscles pipe string,
//  stretch flag when true]. Unmatched package diagnostics remain generator
// output only; they never belong in the browser bundle.

import fs from 'node:fs';
import path from 'node:path';

const manifest = JSON.parse(fs.readFileSync(path.resolve('node_modules/@bryllim/workout-guide/manifest.json'), 'utf8'));
const exercises = manifest;

// Exercise ids live across the split data modules (data.js assembles them
// from src/lib/data/); scan them in assembly order (data.js constants, then
// primary, then coverage) so the generated registry keeps its historical
// insertion order and stays byte-identical across the split.
const DATA_SOURCES = ['src/lib/data.js', 'src/lib/data/exercises-primary.js', 'src/lib/data/exercises-coverage.js', 'src/lib/data/programs.js'];
const ariseSrc = DATA_SOURCES.map(f=> fs.readFileSync(f, 'utf8')).join('\n');
const idRe = /id:\s*'([^']+)'/g;
const ariseIds = new Set();
let m;
while((m = idRe.exec(ariseSrc))) ariseIds.add(m[1]);

const toEntry = ex => ({
  slug: ex.slug,
  name: ex.name,
  exerciseType: ex.exerciseType,
  equipment: ex.equipment,
  frames: ex.frames.map(f => f.index), // every frame the package ships
  primaryMuscle: ex.primaryMuscle,
  secondaryMuscles: ex.secondaryMuscles || [],
  isStretch: !!ex.isStretch,
  license: 'CC BY-SA 4.0',
  creator: 'Bryl Lim',
});

const imageMap = {};
const usedSlugs = new Set();

// Pass 1: direct slug match.
for(const aid of ariseIds){
  const ex = exercises.find(e => e.slug === aid);
  if(ex){
    imageMap[aid] = toEntry(ex);
    usedSlugs.add(ex.slug);
  }
}

// Pass 2: curated aliases for known name differences.
const ALIASES = {
  'bench-press-barbell': 'bench-press',
  'overhead-press-barbell': 'overhead-press',
  'dumbbell-row': 'one-arm-dumbbell-row',
  'cable-row': 'seated-row',
  'tricep-dip-bench': 'dip',
};
for(const [ariseId, slug] of Object.entries(ALIASES)){
  if(!slug || !ariseIds.has(ariseId) || imageMap[ariseId]) continue;
  const ex = exercises.find(e => e.slug === slug);
  if(ex && !usedSlugs.has(ex.slug)){
    imageMap[ariseId] = toEntry(ex);
    usedSlugs.add(ex.slug);
  }
}

// Pass 3: conservative auto-aliases. Strip kit words from BOTH sides and
// accept only when the remaining movement words are UNIQUE in the package and
// unclaimed. Ambiguous cores (bench-press vs dumbbell-bench-press) stay
// unmapped rather than risk showing the wrong illustration.
const KIT_WORDS = new Set(['barbell','dumbbell','dumbbells','machine','cable','cables','kettlebell','band','bands','plate','plates','bodyweight']);
const coreKey = slug => slug.split('-').filter(w => !KIT_WORDS.has(w)).join('|');
const pkgByCore = new Map();
for(const e of exercises){
  const k = coreKey(e.slug);
  if(!pkgByCore.has(k)) pkgByCore.set(k, []);
  pkgByCore.get(k).push(e);
}
const claimedCores = new Set([...usedSlugs].map(s => coreKey(s)));
const autoAliases = [];
for(const aid of [...ariseIds].sort()){
  if(imageMap[aid]) continue;
  const k = coreKey(aid);
  const candidates = pkgByCore.get(k) || [];
  const unclaimed = candidates.filter(e => !usedSlugs.has(e.slug));
  if(candidates.length !== 1 || unclaimed.length !== 1 || claimedCores.has(k)) continue;
  const ex = unclaimed[0];
  imageMap[aid] = toEntry(ex);
  usedSlugs.add(ex.slug);
  claimedCores.add(k);
  autoAliases.push(`${aid} -> ${ex.slug}`);
}

const exerciseTypes = [...new Set(Object.values(imageMap).map(entry => entry.exerciseType))].sort();
const exerciseTypeCode = new Map(exerciseTypes.map((type, index)=> [type, index]));
const runtimeMap = Object.fromEntries(Object.entries(imageMap).map(([id, entry])=> {
  const tuple = [
    entry.slug,
    exerciseTypeCode.get(entry.exerciseType),
    (entry.secondaryMuscles || []).join('|'),
  ];
  if(entry.isStretch) tuple.push(1);
  return [id, tuple];
}));

const frameCounts = new Set(Object.values(imageMap).map(entry => entry.frames.length));
if(frameCounts.size !== 1 || !frameCounts.has(3)){
  throw new Error(`Expected all mapped illustrations to have exactly 3 frames; saw ${[...frameCounts].join(', ')}`);
}

// Output module
const out = `// exerciseImages.js — auto-generated by scripts/generate-exercise-images.mjs
// Illustration source: @bryllim/workout-guide v1.0.0 (302 exercises, 906 SVG frames)
// Assets: CC BY-SA 4.0 © Bryl Lim (https://bryllim.com) — derived from Everkinetic.
// Code: MIT. Attribution must be preserved when shipping these images.
//
// Compact runtime registry: [slug, exerciseTypeCode, secondaryMusclesPipe,
// isStretch?]. Name/equipment/primary muscle come from Arise's canonical data;
// every mapped source record has exactly 3 frames.

import { EXERCISE_BY_ID } from './data.js';

export const IMAGE_BASE = 'https://bryllim.github.io/workout-guide/frames';
const CREATOR = 'Bryl Lim';
const LICENSE = 'CC BY-SA 4.0';
const FRAME_COUNT = 3;
const FRAMES = Object.freeze([1, 2, 3]);
const EXERCISE_TYPES = ${JSON.stringify(exerciseTypes)};

/**
 * Returns { url, alt, name, exerciseType, equipment, primaryMuscle,
 * secondaryMuscles, isStretch, license, creator } or null.
 * frame is 1-based and clamped to the three upstream frames; defaults to 1.
 */
export function getExerciseImage(exerciseId, frame = 1){
  const entry = EXERCISE_IMAGES[exerciseId];
  if(!entry) return null;
  const exercise = EXERCISE_BY_ID[exerciseId];
  const n = Math.max(1, Math.min(FRAME_COUNT, Math.round(frame)));
  const primaryMuscle = exercise?.muscle || '';
  return {
    url: \`\${IMAGE_BASE}/\${entry[0]}/frame-\${n}.svg\`,
    alt: exercise?.name ? \`\${exercise.name} — \${primaryMuscle}\` : \`\${primaryMuscle} exercise\`,
    name: exercise?.name || exerciseId,
    exerciseType: EXERCISE_TYPES[entry[1]],
    equipment: (exercise?.equipment || []).join(', '),
    primaryMuscle,
    secondaryMuscles: entry[2] ? entry[2].split('|') : [],
    isStretch: entry[3] === 1,
    license: LICENSE,
    creator: CREATOR,
  };
}

/** True if this exercise has illustration frames available. */
export function hasExerciseImage(exerciseId){
  return !!EXERCISE_IMAGES[exerciseId];
}

/** All frame indices for an exercise (the full animation sequence). */
export function getImageFrames(exerciseId){
  return EXERCISE_IMAGES[exerciseId] ? FRAMES : [];
}

/**
 * Full package metadata for an exercise: name, exerciseType, equipment,
 * primary/secondary muscles, stretch flag and frame count. Null when unknown.
 */
export function getExerciseMeta(exerciseId){
  const entry = EXERCISE_IMAGES[exerciseId];
  if(!entry) return null;
  const exercise = EXERCISE_BY_ID[exerciseId];
  return {
    name: exercise?.name || exerciseId,
    exerciseType: EXERCISE_TYPES[entry[1]],
    equipment: (exercise?.equipment || []).join(', '),
    primaryMuscle: exercise?.muscle || '',
    secondaryMuscles: entry[2] ? entry[2].split('|') : [],
    isStretch: entry[3] === 1,
    frames: FRAME_COUNT,
    license: LICENSE,
    creator: CREATOR,
  };
}

const EXERCISE_IMAGES = ${JSON.stringify(runtimeMap)};
`;
const outputPath = 'src/lib/exerciseImages.js';
if(process.argv.includes('--check')){
  const current = fs.readFileSync(outputPath, 'utf8');
  if(current !== out){
    console.error('exercise-images: generated registry is stale — run npm run exercise-images:generate');
    process.exit(1);
  }
  console.log('exercise-images: generated registry is up to date');
}else{
  fs.writeFileSync(outputPath, out);
}

const unmatchedCount = exercises.length - usedSlugs.size;
console.log(`Mapped: ${Object.keys(imageMap).length} / ${ariseIds.size} Arise exercises have images`);
console.log(`Auto-aliases added: ${autoAliases.length}`);
for(const a of autoAliases) console.log(`  ${a}`);
console.log(`Package total: ${exercises.length} · still unmatched: ${unmatchedCount}`);
for(const ex of exercises.filter(e => !usedSlugs.has(e.slug))){
  console.log(`  unmatched: ${ex.slug} (${ex.name})`);
}
