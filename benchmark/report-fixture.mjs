#!/usr/bin/env node
// report-fixture.mjs — committed EXAMPLE study reports, generated from a
// deterministic synthetic cohort through the real report pipeline.
//
// Why this exists: `npm run study:report` aggregates REAL consented exports
// into `study-ops-report.md` + `product-success.md`, but until participants
// exist there is nothing to look at. This harness generates the standard
// deterministic field fixture (benchmark/field-fixture.js — 12 synthetic
// participants, 4 exercises × 30 sessions, one repeat export proving dedupe)
// and pushes it through the EXACT ingestion/validation/aggregation/rendering
// path real data takes (ingestParticipantFiles → summariseCohort /
// computeProductSuccessReport). The committed
// benchmark/fixtures/study-ops-report.md and product-success.md are its
// output: a template the operator can read before day one, and a CI-checked
// canary that the report pipeline itself has not drifted.
//
// HONESTY RULES (same as field-study fixture mode):
//   • The reports are clearly bannered as SYNTHETIC EXAMPLES.
//   • generatedAtISO is PINNED (derived from the fixture anchor, not the wall
//     clock) so regeneration is byte-stable; a live run stamps the real time.
//   • Fixture output never overwrites a real report: if the target directory
//     contains reports produced from real exports, this script refuses
//     (pass --force to override deliberately).
//
// Usage:
//   npm run study:report:fixture            # regenerate the committed examples
//   npm run study:report:fixture -- --check # CI: outputs must be byte-identical
//   npm run study:report:fixture -- --out=DIR

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ingestParticipantFiles, summariseCohort, renderCohortReport } from '../src/lib/cohortOps.js';
import { computeProductSuccessReport, renderProductSuccessReport } from '../src/lib/productSuccess.js';
import { syntheticParticipant, FIXTURE_PARTICIPANTS, FIXTURE_START_ISO } from './field-fixture.js';
import { enrollParticipant, assignmentFor } from '../src/lib/studyEnrollment.js';
import { withdrawFromStudy } from '../src/lib/participation.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const checkMode = args.includes('--check');
const force = args.includes('--force');
const outArg = args.find(a => a.startsWith('--out='))?.split('=')[1];
const defaultOut = path.join(here, 'fixtures');

// Pinned "now": the day after the fixture's last session (30 sessions on a
// 3-day cadence from FIXTURE_START_ISO span ~87 days), derived from the anchor
// rather than the clock so regeneration is byte-stable. A real study:report
// run stamps the actual time.
function pinnedNowISO(){
  const anchor = new Date(`${FIXTURE_START_ISO}T00:00:00Z`);
  const last = new Date(anchor.getTime() + 29 * 3 * 86400000); // 30 sessions, 3-day cadence
  const dayAfter = new Date(last.getTime() + 86400000);
  return dayAfter.toISOString();
}

const SYNTHETIC_BANNER =
  '> **SYNTHETIC EXAMPLE — NOT EVIDENCE.** Generated by `npm run study:report:fixture` from a\n' +
  '> deterministic synthetic cohort to exercise the report pipeline and show the report format.\n' +
  '> Real cohort reports are produced by `npm run study:report <exports-dir>` over consented\n' +
  '> participant exports; they carry no such banner and are the only results that mean anything.\n';

// ── Personas ─────────────────────────────────────────────────────────────
// The synthetic cohort should exercise the report's WHOLE schema, so a fixed
// subset of participants gets a real lifecycle attached using the app's own
// functions (joinStudy/withdrawFromStudy semantics — not hand-rolled fields):
//   • participants 0–8: enrolled via enrollParticipant (deterministic arms),
//     with ledger assignedArm aligned to the enrollment's frozen assignment —
//     cohortOps flags an exercise assigned to different arms across exports
//     of one person, so the fixture must carry consistent arms;
//   • participant 9: enrolled, then withdrew near the pinned date — history
//     preserved (withdrawal stops treatment, never erases it);
//   • participants 10–11: log truncated after week 1, never enrolled — they
//     show up as lapsed/dropout in activity and as missing week-4 retention.
// applyPersona is deterministic: same index ⇒ same persona ⇒ byte-stable
// reports.
function applyPersona(index, store){
  if(index >= 10){
    // Lapsed/dropout persona: log truncated after week 1 (4 sessions at the
    // 3-day cadence), nothing enrolled. The app never writes assigned-arm
    // rows for an un-enrolled participant (studyArmFor returns null), so the
    // persona's ledger rows lose their arm labels too.
    const cutoffDate = store.history[3].dateISO;
    return {
      ...store,
      history: store.history.filter(h => h.dateISO <= cutoffDate),
      activeSchedule: {
        ...store.activeSchedule,
        sessions: store.activeSchedule.sessions.map(s => ({ ...s, status: s.dateISO <= cutoffDate ? 'done' : 'planned' })),
      },
      eventHistory: store.eventHistory.filter(e => e.at.slice(0, 10) <= cutoffDate),
      evaluationLedger: store.evaluationLedger
        .filter(r => r.outcome?.dateISO <= cutoffDate)
        .map(r => ({ ...r, assignedArm: null, prescription: { ...r.prescription, arm: null }, outcome: { ...r.outcome, assignedArm: null } })),
    };
  }
  const exerciseIds = ['bench-press-dumbbell', 'goblet-squat', 'romanian-deadlift', 'lat-pulldown'];
  const enrolledAt = new Date(Date.parse(`${FIXTURE_START_ISO}T00:00:00Z`) + 86400000).toISOString();
  const enrollment = enrollParticipant({ participantId: store.studyParticipantId, exerciseIds, nowISO: enrolledAt });
  let withEnrollment = { ...store, studyEnrollment: enrollment, studyStatus: 'enrolled', studyStatusChangedAtISO: enrolledAt };
  // Align ledger arms with the enrollment's frozen assignment so the
  // preserved history matches what the app actually assigned (2 lifts per
  // arm per person). The prescription's per-arm snapshot keeps its own
  // (already honest) numbers; only the labels move.
  withEnrollment = {
    ...withEnrollment,
    evaluationLedger: withEnrollment.evaluationLedger.map(r => {
      const arm = assignmentFor(withEnrollment.studyEnrollment, r.exerciseId) || r.assignedArm;
      if(arm === r.assignedArm) return r;
      return {
        ...r,
        assignedArm: arm,
        prescription: { ...r.prescription, arm },
        outcome: { ...r.outcome, assignedArm: arm },
      };
    }),
  };
  if(index === 9){
    // Withdrawn near the pinned date; withdrawal preserves observed history
    // (aligned arms stay on the rows — that is the point of preservation).
    withEnrollment = withdrawFromStudy(withEnrollment, { nowISO: pinnedNowISO() });
  }
  return withEnrollment;
}

async function buildReports(){
  const files = [];
  for(let i = 0; i < FIXTURE_PARTICIPANTS; i++){
    files.push({ name: `fixture-participant-${String(i + 1).padStart(2, '0')}.json`, text: JSON.stringify(applyPersona(i, syntheticParticipant(i))) });
  }
  // The FIRST participant re-exports later — same study id, cumulative log.
  // This proves the merge path folds repeated exports into one participant.
  files.push({ name: 'fixture-participant-01-reexport.json', text: JSON.stringify(applyPersona(0, syntheticParticipant(0))) });

  const nowISO = pinnedNowISO();
  const ingest = await ingestParticipantFiles(files);
  const cohort = summariseCohort(ingest.participants, { nowISO });
  const success = computeProductSuccessReport(ingest.participants, { nowISO });

  const cohortMd = renderCohortReport(cohort, { ingest });
  const successMd = renderProductSuccessReport(success);
  return { cohortMd, successMd, ingest, cohort, nowISO, exportCount: files.length };
}

function injectBanner(md){
  // Insert directly under the report's first heading line.
  if(!md.startsWith('# ')) throw new Error('report does not start with a top-level heading — banner placement failed');
  const heading = md.slice(0, md.indexOf('\n') + 1);
  return heading + '\n' + SYNTHETIC_BANNER + md.slice(heading.length);
}

const { cohortMd, successMd, ingest, cohort, nowISO, exportCount } = await buildReports();
const cohortOut = injectBanner(cohortMd);
const successOut = injectBanner(successMd);

const outDir = path.resolve(outArg || defaultOut);
const cohortPath = path.join(outDir, 'study-ops-report.md');
const successPath = path.join(outDir, 'product-success.md');

function guardRealReports(){
  for(const p of [cohortPath, successPath]){
    if(!fs.existsSync(p) || force) continue;
    const text = fs.readFileSync(p, 'utf8');
    if(!text.includes(SYNTHETIC_BANNER.slice(0, 40))){
      console.error(`Refusing to overwrite ${p}: it does not carry the synthetic banner, so it looks like a REAL report.`);
      console.error('Move it aside or re-run with --force to overwrite deliberately.');
      process.exit(1);
    }
  }
}

if(checkMode){
  const problems = [];
  for(const [p, expected] of [[cohortPath, cohortOut], [successPath, successOut]]){
    if(!fs.existsSync(p)){ problems.push(`missing: ${p}`); continue; }
    const actual = fs.readFileSync(p, 'utf8');
    if(actual !== expected){
      const lines = expected.split('\n');
      const actualLines = actual.split('\n');
      let diffAt = 0;
      while(diffAt < lines.length && diffAt < actualLines.length && lines[diffAt] === actualLines[diffAt]) diffAt++;
      problems.push(`stale: ${p} (first differing line ${diffAt + 1})`);
    }
  }
  if(problems.length){
    console.error('report-fixture --check FAILED:');
    for(const problem of problems) console.error(`  - ${problem}`);
    console.error('Regenerate with `npm run study:report:fixture` and commit the results.');
    process.exit(1);
  }
  console.log(`report-fixture --check OK: committed example reports match the current pipeline (pinned now=${nowISO.slice(0, 10)}).`);
  process.exit(0);
}

guardRealReports();
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(cohortPath, cohortOut);
fs.writeFileSync(successPath, successOut);

console.log(`${cohortOut}\n\n${successOut}`);
console.log(`Written: ${cohortPath}`);
console.log(`Written: ${successPath}`);
console.log(`Fixture: ${exportCount} synthetic exports → ${ingest.counts.uniqueParticipants} unique participant(s), ${ingest.counts.duplicateFiles} duplicate file(s) folded, ${ingest.counts.importErrors} import error(s), ${ingest.warnings.length} warning(s); gate eligible=${cohort.gate.eligible} (pinned now=${nowISO.slice(0, 10)}).`);
console.log('These are EXAMPLE reports over synthetic data — never cite them as results.');
